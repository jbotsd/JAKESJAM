// ── draft (2026-07-14) — native card-drafting offer generation ──────────
// Golden vectors generated by running the REAL TS draftWeights.ts +
// round.ts enterDrafting loop against the real crystalRoundsCards table
// (see sim/tools/gen_card_data.ts's comment + the throwaway generator
// script this was produced with — re-run if cards.ts or the weighting
// formula changes). This proves RNG-cursor AND selection parity against
// TS, not just "the Zig code runs" — every offer index and final cursor
// below is what TS itself produced for the same seed.

fn allTrueBools(comptime n: usize) [n]bool {
    var a: [n]bool = @splat(false);
    var i: usize = 0;
    while (i < n) : (i += 1) a[i] = true;
    return a;
}

test "draft.rollOffers: catch_up role, full 60-card pool, seed=12345 matches TS" {
    var pool_buf: [root.draft.gen.cards.len]u32 = undefined;
    for (0..root.draft.gen.cards.len) |i| pool_buf[i] = @intCast(i);
    const result = root.draft.rollOffers(12345, &pool_buf, .catch_up);
    try std.testing.expectEqual(@as(u32, 3), result.count);
    try std.testing.expectEqual(@as(u32, 59), result.offers[0]); // stolen-fangs
    try std.testing.expectEqual(@as(u32, 55), result.offers[1]); // bulwark-core
    try std.testing.expectEqual(@as(u32, 38), result.offers[2]); // heavy-coolant
    try std.testing.expectEqual(@as(u32, 2400459792), result.cursor);
}

test "draft.rollOffers: winner role (uniform weight), full pool, seed=12345 matches TS" {
    var pool_buf: [root.draft.gen.cards.len]u32 = undefined;
    for (0..root.draft.gen.cards.len) |i| pool_buf[i] = @intCast(i);
    const result = root.draft.rollOffers(12345, &pool_buf, .winner);
    try std.testing.expectEqual(@as(u32, 3), result.count);
    try std.testing.expectEqual(@as(u32, 58), result.offers[0]); // riot-mirror
    try std.testing.expectEqual(@as(u32, 54), result.offers[1]); // blink-dash
    try std.testing.expectEqual(@as(u32, 32), result.offers[2]); // frost-prism
    // Same cursor evolution as the catch_up case above: pickWeighted draws
    // exactly one nextFloat per call regardless of weights, so with the same
    // pool size and same number of loop iterations the cursor is identical
    // to the catch_up vector even though the picks differ — a structural
    // invariant confirmed against TS, not a coincidence.
    try std.testing.expectEqual(@as(u32, 2400459792), result.cursor);
}

