test "draft.poolIndices: unique cards already owned are excluded" {
    // Find any unique card in the real table to drive the test off real data
    // instead of a fabricated fixture.
    var unique_idx: ?usize = null;
    for (root.draft.gen.cards, 0..) |entry, i| {
        if (entry.unique) {
            unique_idx = i;
            break;
        }
    }
    try std.testing.expect(unique_idx != null);
    const owned = allTrueBools(root.draft.gen.cards.len);
    var not_owned: [root.draft.gen.cards.len]bool = @splat(false);
    const copies: [root.draft.gen.cards.len]u32 = @splat(0);
    var out_owned: [root.draft.gen.cards.len]u32 = undefined;
    var out_not_owned: [root.draft.gen.cards.len]u32 = undefined;
    const n_owned = root.draft.poolIndices(&owned, &copies, &out_owned);
    const n_not_owned = root.draft.poolIndices(&not_owned, &copies, &out_not_owned);
    // Every unique card should be present when nothing is "owned"...
    var found_in_not_owned = false;
    for (out_not_owned[0..n_not_owned]) |idx| {
        if (idx == unique_idx.?) found_in_not_owned = true;
    }
    try std.testing.expect(found_in_not_owned);
    // ...and absent when everything is "owned".
    var found_in_owned = false;
    for (out_owned[0..n_owned]) |idx| {
        if (idx == unique_idx.?) found_in_owned = true;
    }
    try std.testing.expect(!found_in_owned);
}

test "draft.poolIndices: maxStacks cap excludes cards already at cap" {
    var capped_idx: ?usize = null;
    var cap_value: u32 = 0;
    for (root.draft.gen.cards, 0..) |entry, i| {
        if (entry.max_stacks) |cap| {
            capped_idx = i;
            cap_value = cap;
            break;
        }
    }
    try std.testing.expect(capped_idx != null);
    const owned: [root.draft.gen.cards.len]bool = @splat(false);
    var copies: [root.draft.gen.cards.len]u32 = @splat(0);
    copies[capped_idx.?] = cap_value; // at cap
    var out: [root.draft.gen.cards.len]u32 = undefined;
    const n = root.draft.poolIndices(&owned, &copies, &out);
    var found = false;
    for (out[0..n]) |idx| {
        if (idx == capped_idx.?) found = true;
    }
    try std.testing.expect(!found);
}
